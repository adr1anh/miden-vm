#[tokio::test(flavor = "current_thread")]
async fn mixed_signatures_deferred_obligation_is_settled_end_to_end() {
    let core_lib = CoreLibrary::default();
    let ed25519_key = Ed25519SigningKey::read_from_bytes(&[0xed; 32]).unwrap();
    let (deferred_proof, claim, precompile_witness) = prove_signature_execution(
        &core_lib,
        valid_fixture(),
        Some(&ed25519_key),
        StackInputs::default(),
    );
    let outcome = Verifier::new()
        .verify(&claim, &deferred_proof)
        .expect("the MVM proof must authenticate its deferred obligation");
    let deferred_root = outcome
        .outstanding_precompile_root()
        .expect("the signature execution must retain a deferred obligation");

    let settlement = run_settlement_in_masm(&core_lib, &deferred_proof, &claim, precompile_witness)
        .await
        .expect("failed to settle the deferred root");
    assert_eq!(
        settlement.precompile_proof.roots,
        [deferred_root],
        "the PVM proof must cover the MVM verifier's deferred root",
    );
    assert_eq!(
        settlement.output.stack.get_num_elements(4),
        vec![Felt::ZERO; 4],
        "settlement must consume the deferred root rather than return it",
    );

    let final_proof = deferred_proof
        .complete(settlement.precompile_proof)
        .expect("a deferred execution proof must accept its precompile proof");
    let outcome = Verifier::new()
        .verify(&claim, &final_proof)
        .expect("native final verification must accept the proof generated by the event");
    assert!(outcome.is_complete(), "the PVM proof must discharge the obligation");
}

/// Proves an ECDSA execution and returns its portable precompile witness for the PVM prover.
fn prove_ecdsa_execution(
    core_lib: &CoreLibrary,
    fixture: EcdsaFixture,
    stack_inputs: StackInputs,
) -> (ExecutionProof, ExecutionClaim, PrecompileWitness) {
    prove_signature_execution(core_lib, fixture, None, stack_inputs)
}

/// Proves an ECDSA execution, optionally followed by an Ed25519 verification of the same message,
/// and returns its portable precompile witness for the PVM prover.
fn prove_signature_execution(
    core_lib: &CoreLibrary,
    fixture: EcdsaFixture,
    ed25519_key: Option<&Ed25519SigningKey>,
    stack_inputs: StackInputs,
) -> (ExecutionProof, ExecutionClaim, PrecompileWitness) {
    let ed25519_verify = ed25519_key
        .map(|key| {
            let commitment = eddsa_25519_sha512::public_key_commitment(&key.public_key());
            format!(
                "{}\n            {}\n            \
                 exec.::miden::core::crypto::dsa::eddsa_25519_sha512::verify",
                masm_push_word(&fixture.message),
                masm_push_word(&commitment),
            )
        })
        .unwrap_or_default();
    let source = format!(
        "
        begin
            {}
            {}
            exec.::miden::core::crypto::dsa::ecdsa_k256_keccak::verify
            {ed25519_verify}
        end
        ",
        masm_push_word(&fixture.message),
        masm_push_word(&fixture.public_key_commitment),
    );
    let program = assemble(
        Assembler::default()
            .with_package(core_lib.code_package().clone(), Linkage::Dynamic)
            .expect("core library must link"),
        "signature_deferred_settlement",
        source,
        &[core_lib.naming()],
    );
    let mut host = DefaultHost::default()
        .with_environment_source(program.1.source())
        .with_library(program.0.clone())
        .expect("fixture code must load into the host")
        .with_library(core_lib)
        .expect("core library must load into the host");
    let mut advice_stack = AdviceStack::new();
    advice_stack.append_elements(fixture.advice);
    if let Some(key) = ed25519_key {
        advice_stack.append_elements(eddsa_25519_sha512::sign(key, fixture.message));
    }
    let witness = FastProcessor::new_with_options(
        stack_inputs,
        AdviceInputs::default().with_stack(advice_stack),
        ExecutionOptions::default()
            .with_resolution_limits(program.1.resolution_limits())
            .with_environment_trace_limits(miden_utils_testing::librarytree::trace_limits()),
    )
    .expect("signature advice must fit provider limits")
    .execute_for_proving_sync(program.1.target(), &mut host)
    .expect("signature execution must produce a proving witness");
    let claim = witness.claim();
    // The core library's recursive verifiers accept Eidos proofs.
    let proof = Prover::new()
        .with_hash_fn(HashFunction::Eidos)
        .prove(witness)
        .expect("signature execution must produce a deferred MVM proof");
    let PrecompileStatus::Deferred(precompile) = proof.precompile() else {
        panic!("signature execution must retain deferred precompile work")
    };
    let precompile_witness = precompile.clone();

    (proof, claim, precompile_witness)
}

struct SettlementResult {
    output: ExecutionOutput,
    precompile_proof: PrecompileProof,
}

async fn run_settlement_in_masm(
    core_lib: &CoreLibrary,
    deferred_proof: &ExecutionProof,
    claim: &ExecutionClaim,
    precompile_witness: PrecompileWitness,
) -> Result<SettlementResult, miden_processor::ExecutionError> {
    let vm = RecursiveVerifierInputs::for_request(
        core_lib.vm_recursive_verifier_profile().unwrap().identity(),
        deferred_proof,
        claim,
    )
    .expect("partial MVM proof must adapt to recursive-verifier advice");
    let (advice_inputs, claim_commitment) = vm.into_parts();
    assert!(advice_inputs.stack().is_empty(), "the MVM proof stream must be map-backed");

    let stack_inputs = StackInputs::new(claim_commitment.as_elements())
        .expect("claim commitment must fit the stack");
    let program = assemble_settlement_program(core_lib);
    let mut host =
        PvmSettlementHost::new(core_lib, &program, &advice_inputs, vec![precompile_witness]);

    let output = FastProcessor::new_with_options(
        stack_inputs,
        advice_inputs,
        ExecutionOptions::default().with_resolution_limits(program.1.resolution_limits()),
    )
    .expect("failed to construct FastProcessor")
    .execute(program.1.target(), &mut host)
    .await?;
    let precompile_proof = host
        .precompile_proof
        .take()
        .expect("successful settlement must retain the generated proof");

    Ok(SettlementResult { output, precompile_proof })
}

fn assemble_settlement_program(core_lib: &CoreLibrary) -> NamedProgram {
    let guide =
        include_str!("../../../../../docs/src/user_docs/core_lib/recursive_verification.md");
    let (_, example) = guide
        .split_once("```masm title=\"settle_deferred.masm\"\n")
        .expect("guide must contain the settlement example");
    let (source, _) = example.split_once("\n```").expect("settlement code block must be closed");

    let source = format!("{}\n{source}", verifier_identity_constants(core_lib));
    let program = assemble(
        Assembler::default()
            .with_package(core_lib.code_package().clone(), Linkage::Dynamic)
            .expect("core library must link"),
        "async_pvm_settlement",
        source,
        &[core_lib.naming()],
    );
    mount_settlement_verifier(core_lib, program)
}

/// Outer program constants come from this fixture owner's selected embedded profiles. They are
/// never definitions in the core fragment whose configuration the identities commit to.
fn verifier_identity_constants(core_lib: &CoreLibrary) -> String {
    let vm = core_lib.vm_recursive_verifier_profile().unwrap();
    let pvm = core_lib.pvm_recursive_verifier_profile().unwrap();
    [
        ("VM_VERIFIER_IDENTITY", vm.identity()),
        ("PVM_VERIFIER_IDENTITY", pvm.identity()),
    ]
    .into_iter()
    .map(|(name, identity)| {
        let values = identity
            .as_word()
            .iter()
            .map(|felt| felt.as_canonical_u64().to_string())
            .collect::<Vec<_>>()
            .join(", ");
        format!("const {name} = [{values}]\n")
    })
    .collect()
}

fn mount_settlement_verifier(core_lib: &CoreLibrary, mut program: NamedProgram) -> NamedProgram {
    let vm = core_lib.vm_recursive_verifier_profile().unwrap();
    let pvm = core_lib.pvm_recursive_verifier_profile().unwrap();
    assert_eq!(vm.fragment().root(), pvm.fragment().root());
    program.1 = FixtureEnvironment::new_with_fragments(
        program.0.symbols().entry_key().expect("settlement program must have an entry"),
        [program.0.symbols().as_ref(), core_lib.naming()],
        &[vm.shared_fragment()],
    )
    .expect("the complete core fragment must mount in the settlement environment");
    program
}

fn authorize_settlement_vm(core_lib: &CoreLibrary, program: &NamedProgram, advice: &AdviceInputs) {
    let mut effective_advice = advice.map().clone();
    effective_advice
        .merge(program.0.package().mast_forest().advice_map())
        .expect("outer program advice must not conflict with request advice");
    effective_advice
        .merge(core_lib.mast_forest().advice_map())
        .expect("core package advice must not conflict with request advice");
    let environment = program.1.validated_environment();
    core_lib
        .vm_recursive_verifier_profile()
        .unwrap()
        .authorize(environment.root(), environment, &effective_advice, environment.visits())
        .expect("the initial VM verifier environment and resources must authorize");
}

/// Generates a PVM proof from its witness when `pvm::request_proof` emits an event.
struct PvmSettlementHost {
    inner: DefaultHost,
    event_name: EventName,
    expected_verifier: VerifierIdentity,
    verifier_profile: CoreVerifierProfile,
    environment: FixtureEnvironment,
    available_root: Word,
    precompile_witnesses: Vec<PrecompileWitness>,
    precompile_proof: Option<PrecompileProof>,
}

impl PvmSettlementHost {
    fn new(
        core_lib: &CoreLibrary,
        program: &NamedProgram,
        advice: &AdviceInputs,
        precompile_witnesses: Vec<PrecompileWitness>,
    ) -> Self {
        // The initial VM package authenticates the complete shared core mount. The PVM ACE
        // resource arrives with the event response and is checked before it is supplied.
        authorize_settlement_vm(core_lib, program, advice);
        let verifier_profile = core_lib.pvm_recursive_verifier_profile().unwrap();
        let expected_verifier = verifier_profile.identity();
        let inner = DefaultHost::default()
            .with_environment_source(program.1.source())
            .with_library(program.0.clone())
            .expect("fixture code must load into the host")
            .with_library(core_lib)
            .expect("core library must load into the settlement host");
        let registry = Arc::new(miden_precompiles::registry());
        let limits = miden_precompiles::default_verification_precompile_limits();
        let available_root = precompile_witnesses
            .iter()
            .map(|witness| {
                witness
                    .clone()
                    .prepare(Arc::clone(&registry), &limits)
                    .expect("execution-produced witness must prepare")
                    .root()
            })
            .reduce(fold_deferred_root)
            .expect("settlement requires at least one witness");
        Self {
            inner,
            event_name: PVM_PROOF_REQUEST_EVENT_NAME,
            expected_verifier,
            verifier_profile,
            environment: program.1.clone(),
            available_root,
            precompile_witnesses,
            precompile_proof: None,
        }
    }
}

impl BaseHost for PvmSettlementHost {
    fn get_label_and_source_file(
        &self,
        location: &Location,
    ) -> (SourceSpan, Option<Arc<SourceFile>>) {
        BaseHost::get_label_and_source_file(&self.inner, location)
    }

    fn resolve_event(&self, event_id: EventId) -> Option<&EventName> {
        if event_id == PVM_PROOF_REQUEST_EVENT_NAME.to_event_id() {
            Some(&self.event_name)
        } else {
            BaseHost::resolve_event(&self.inner, event_id)
        }
    }
}

impl Host for PvmSettlementHost {
    fn get_environment_witness(
        &mut self,
        request: EnvironmentWitnessRequest,
    ) -> impl FutureMaybeSend<Result<Option<ResolutionWitness>, EnvironmentSourceError>> {
        let witness = SyncHost::get_environment_witness(&mut self.inner, request);
        async move { witness }
    }

    fn get_mast_forest(
        &self,
        request: miden_processor::CodeRequest,
    ) -> impl FutureMaybeSend<Option<LoadedMastForest>> {
        let forest = SyncHost::get_mast_forest(&self.inner, request);
        async move { forest }
    }

    fn on_event(
        &mut self,
        process: &ProcessorState<'_>,
    ) -> impl FutureMaybeSend<Result<Vec<AdviceMutation>, EventError>> {
        async move {
            let event_id = EventId::from_felt(process.get_stack_item(0));
            if event_id != PVM_PROOF_REQUEST_EVENT_NAME.to_event_id() {
                return SyncHost::on_event(&mut self.inner, process);
            }

            // The event stack is [event_id, V, D, D, ...]. V and the requested D start at
            // positions 1 and 5; the preserved D starts at 9.
            let verifier_word = process.get_stack_word(1);
            let requested_root = process.get_stack_word(5);
            if verifier_word != self.expected_verifier.into_word() {
                return Err(SettlementEventError::VerifierIdentityMismatch {
                    requested: verifier_word,
                    expected: self.expected_verifier,
                }
                .into());
            }
            if requested_root != self.available_root {
                return Err(SettlementEventError::RootMismatch {
                    requested: requested_root,
                    available: self.available_root,
                }
                .into());
            }

            let proof_key = proof_request_key(self.expected_verifier, requested_root);
            if process.advice_provider().map().get(&proof_key).is_some() {
                return Err(SettlementEventError::PackageAlreadyLoaded.into());
            }

            // This host yields once, then proves locally. A host using a remote prover could
            // await its response here.
            tokio::task::yield_now().await;
            let precompile_proof = Prover::new()
                .with_hash_fn(HashFunction::Eidos)
                .prove_precompiles(self.precompile_witnesses.clone())
                .map_err(SettlementEventError::Proving)?;
            // Package the proof under the request key. MASM fetches it when request_proof returns.
            let package =
                PvmRecursiveVerifierInputs::for_request(self.expected_verifier, &precompile_proof)
                    .map_err(SettlementEventError::Advice)?;
            let (advice, _) = package.into_parts();
            let (_, advice_map, store) = advice.into_parts();
            authorize_pvm_response(
                &self.verifier_profile,
                &self.environment,
                process.advice_provider().map(),
                &advice_map,
            )?;
            let merkle_nodes = store.inner_nodes();
            self.precompile_proof = Some(precompile_proof);

            Ok(vec![
                AdviceMutation::extend_map(advice_map),
                AdviceMutation::extend_merkle_store(merkle_nodes),
            ])
        }
    }
}

fn authorize_pvm_response(
    profile: &CoreVerifierProfile,
    fixture: &FixtureEnvironment,
    current_advice: &AdviceMap,
    supplied_advice: &AdviceMap,
) -> Result<(), SettlementEventError> {
    let mut effective_advice = current_advice.clone();
    effective_advice
        .merge(supplied_advice)
        .map_err(|_| SettlementEventError::AdviceConflict)?;
    let environment = fixture.validated_environment();
    profile
        .authorize(environment.root(), environment, &effective_advice, environment.visits())
        .map_err(SettlementEventError::Authorization)
}

#[derive(Debug, thiserror::Error)]
enum SettlementEventError {
    #[error(
        "requested verifier identity {requested:?} does not match expected identity {expected:?}"
    )]
    VerifierIdentityMismatch {
        requested: Word,
        expected: VerifierIdentity,
    },
    #[error("the supplied PVM advice conflicts with advice already loaded")]
    AdviceConflict,
    #[error("the PVM verifier environment or resources do not authorize: {0}")]
    Authorization(#[source] CoreVerifierProfileError),
    #[error("requested deferred root {requested:?} does not match available root {available:?}")]
    RootMismatch { requested: Word, available: Word },
    #[error("a PVM proof package was already loaded before the settlement event")]
    PackageAlreadyLoaded,
    #[error("PVM proof generation failed: {0}")]
    Proving(#[source] ProverError),
    #[error("PVM recursive-verifier advice construction failed: {0}")]
    Advice(#[source] PvmRecursiveVerifierInputsError),
}
